#                                                                       DEVICES
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
# Compose refuses to start a service whose `devices:` path does not exist, and
# the error names the path without saying which overlay asked for it.

check_devices() {
    [[ -n "$DETECTOR" ]] || return 0
    log_step "Checking device nodes for the $DETECTOR profile..."

    case "$DETECTOR" in
        openvino)
            if [[ -e /dev/dri/renderD128 ]]; then
                log_ok "/dev/dri/renderD128 is present."
            else
                fail "/dev/dri/renderD128 does not exist. No Intel render node on this host."
                log_next "ls -l /dev/dri/   — a second GPU may put it at renderD129; edit compose.openvino.yaml."
                log_next "On a Raspberry Pi or Gateworks board there is no Intel GPU. Use coral-usb, hailo, rpi or cpu."
            fi
            local rgid; rgid="$(env_get RENDER_GID)"
            local real; real="$(getent group render 2>/dev/null | cut -d: -f3 || true)"
            if [[ -n "$real" && -n "$rgid" && "$real" != "$rgid" ]]; then
                warn "RENDER_GID is $rgid but this host's render group is $real. Frigate will get EACCES on the render node."
            fi
            ;;
        coral-usb)
            if [[ -d /dev/bus/usb ]]; then
                log_ok "/dev/bus/usb is present."
            else
                fail "/dev/bus/usb does not exist. No USB subsystem to hand the container."
            fi
            if command -v lsusb >/dev/null 2>&1; then
                if lsusb 2>/dev/null | grep -qiE '18d1:9302|1a6e:089a|Global Unichip|Google Inc'; then
                    log_ok "A Coral accelerator is on the bus."
                else
                    warn "No Coral found by lsusb. It enumerates as 1a6e:089a cold and 18d1:9302 after firmware upload."
                fi
            fi
            ;;
        hailo)
            if [[ -e /dev/hailo0 ]]; then
                log_ok "/dev/hailo0 is present."
            else
                fail "/dev/hailo0 does not exist. The Hailo driver is not loaded."
                log_next "sudo apt install hailo-all && sudo reboot"
                log_next "The Raspberry Pi AI Camera (IMX500) is not this device. Only the M.2 Hailo module works."
            fi
            ;;
        rpi)
            if [[ -e /dev/video11 ]]; then
                log_ok "/dev/video11 is present."
            else
                fail "/dev/video11 does not exist."
                log_next "A Raspberry Pi 5 has no hardware H.264 decoder and never exposes it. Use compose.cpu.yaml there."
            fi
            ;;
        cpu)
            log_ok "No devices needed."
            ;;
    esac
}

