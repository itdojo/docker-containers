main() {
    parse_args "$@"
    check_for_root

    banner "FRIGATE SETUP" "$(host_model)"

    seed_if_missing

    log_phase "PREFLIGHT"
    check_docker
    check_profile
    check_detector_agreement
    check_devices
    check_storage
    check_jwt_secret
    check_wireguard
    check_compose_valid

    log_phase "SUMMARY"
    if (( FAILURES )); then
        log_err "$FAILURES problem(s) must be fixed before the stack will run."
        (( WARNINGS )) && log_warn "$WARNINGS warning(s) as well."
        exit 1
    fi

    if (( WARNINGS )); then
        log_warn "$WARNINGS warning(s). Nothing blocking."
    else
        log_ok "All checks passed."
    fi

    if (( CHECK_ONLY )); then
        log_info "--check given; stopping without starting anything."
        exit 0
    fi

    if bring_up; then
        show_admin_password
        report
        log_complete "FRIGATE IS RUNNING"
    fi
}

main "$@"
