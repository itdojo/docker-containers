# frigate-setup.sh
#
# Preflight and first run for the Frigate stack. Everything it checks is
# something that otherwise fails late, quietly, or as a symptom that points
# somewhere other than the cause: a detector overlay that disagrees with
# config.yml, a device node the host does not have, recordings aimed at an SD
# card, a JWT secret that changes on every restart.
#
# Usage:  ./frigate-setup.sh [-c|--check] [-y|--yes] [-h|--help]
#
#   -c, --check   Run every check and stop. Touches nothing, starts nothing.
#   -y, --yes     Take the default at every prompt. For unattended rebuilds.
#
# Do not run as root. It uses sudo per step and refuses an EUID of 0.
# It is idempotent — rerun it as often as you like.
#
# On a first run it will hand you the generated admin password. That password
# is in the container log, and on 0.17.2 any authenticated user can read the
# container log. Change it at Settings > Users before you create a second
# account. The README says this again, at more length, and means it.
