#                                                                     WIREGUARD
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒

# IPv4 dotted quad -> integer. Returns 1 on anything that is not one, so
# callers can skip IPv6 and malformed entries rather than comparing garbage.
_ip2int() {
    local a b c d IFS=.
    [[ "$1" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]] || return 1
    read -r a b c d <<<"$1"
    (( a < 256 && b < 256 && c < 256 && d < 256 )) || return 1
    printf '%s' $(( (a << 24) | (b << 16) | (c << 8) | d ))
}

# Do two CIDRs cover any address in common? Mask both to the SHORTER prefix and
# compare: if the networks match there, one contains the other. Returns 0 on
# overlap.
_cidr_overlap() {
    local a="${1%%/*}" la="${1##*/}" b="${2%%/*}" lb="${2##*/}" ai bi m sh
    [[ "$la" =~ ^[0-9]+$ ]] && (( la <= 32 )) || la=32
    [[ "$lb" =~ ^[0-9]+$ ]] && (( lb <= 32 )) || lb=32
    ai="$(_ip2int "$a")" || return 1
    bi="$(_ip2int "$b")" || return 1
    m=$(( la < lb ? la : lb ))
    (( m == 0 )) && return 0
    sh=$(( 32 - m ))
    (( (ai >> sh) == (bi >> sh) ))
}

# Every IPv4 network this host can already reach directly: real NICs, docker0,
# every br-* bridge, plus the subnets of Docker networks that have no live
# bridge yet. Tunnel interfaces are excluded — those are the far side.
#
# Every source is individually tolerated. Under `set -e` with pipefail a
# missing `ip` used to abort the whole function, which left the caller
# comparing against an empty list and reporting "no overlap" — a check that
# passes because it did not run. The caller now counts what it got.
_local_subnets() {
    local nets addr mask bits m

    if command -v ip >/dev/null 2>&1; then
        ip -o -f inet addr show 2>/dev/null \
            | awk '$2 !~ /^(lo|wg|tun|tap)/ {print $4}' || true
    elif command -v ifconfig >/dev/null 2>&1; then
        # BSD/macOS, for authoring. Deployment hosts have `ip`. ifconfig
        # reports a hex netmask, so turn it into a prefix length by counting
        # bits.
        while read -r addr mask; do
            [[ "$addr" =~ ^[0-9] ]] || continue
            [[ "$mask" == 0x* ]] || continue
            m=$(( mask )); bits=0
            while (( m > 0 )); do bits=$(( bits + (m & 1) )); m=$(( m >> 1 )); done
            printf '%s/%s\n' "$addr" "$bits"
        done < <(ifconfig 2>/dev/null | awk '/inet /{print $2, $4}') || true
    fi

    nets="$(docker network ls -q 2>/dev/null || true)"
    [[ -z "$nets" ]] && return 0
    # shellcheck disable=SC2086
    docker network inspect $nets \
        --format '{{range .IPAM.Config}}{{.Subnet}}{{"\n"}}{{end}}' 2>/dev/null || true
    return 0
}

# The mixed-ingest failure mode: a prefix in AllowedIPs that also covers
# something local silently captures it. The far-end LAN sharing a private
# range with the near-end LAN is the common case, and the symptom — local
# cameras dropping the moment the tunnel comes up — points nowhere near
# wg0.conf. Docker's own bridge pool is the same hazard for the broker.
check_allowedips_overlap() {
    local line allowed=() prefix local_net hits=0 compared=0

    line="$(grep -E '^[[:space:]]*AllowedIPs[[:space:]]*=' "$WG_CONF" | tail -n1 || true)"
    [[ -z "$line" ]] && { warn "wg0.conf has no AllowedIPs line. The tunnel will route nothing."; return; }

    # shellcheck disable=SC2206
    allowed=( ${line#*=} )
    allowed=( "${allowed[@]//,/}" )

    while IFS= read -r local_net; do
        [[ -z "$local_net" || "$local_net" == *:* ]] && continue
        compared=$(( compared + 1 ))
        for prefix in "${allowed[@]}"; do
            [[ -z "$prefix" || "$prefix" == *:* ]] && continue
            if _cidr_overlap "$prefix" "$local_net"; then
                fail "AllowedIPs $prefix overlaps this host's own network $local_net."
                hits=$(( hits + 1 ))
            fi
        done
    done < <(_local_subnets | sort -u)

    if (( hits )); then
        log_next "That prefix captures local traffic into the tunnel. LAN cameras, or mosquitto, stop answering."
        log_next "Fix on the far end: renumber that network, or narrow AllowedIPs to the camera addresses."
    elif (( compared == 0 )); then
        # Never report a pass we did not earn.
        warn "Could not enumerate this host's networks; the AllowedIPs overlap check did not run."
        log_next "Install iproute2, or compare AllowedIPs against 'ip addr' and your Docker subnets by hand."
    else
        log_ok "AllowedIPs does not overlap any of $compared local network(s)."
    fi
}

check_wireguard() {
    [[ "$NETWORK" == "wireguard" ]] || return 0
    log_step "Checking the WireGuard sidecar..."

    if [[ ! -f "$WG_CONF" ]]; then
        if (( CHECK_ONLY )); then
            fail "compose.wireguard.yaml is selected but wireguard/wg0.conf does not exist."
            log_next "cp wireguard/wg0.conf.example wireguard/wg0.conf && \$EDITOR wireguard/wg0.conf"
            return
        fi
        cp "$SCRIPT_DIR/wireguard/wg0.conf.example" "$WG_CONF"
        chmod 600 "$WG_CONF"
        fail "Created wireguard/wg0.conf from the example. It is a template, not a working tunnel."
        log_next "\$EDITOR $WG_CONF   — keys, Endpoint, and AllowedIPs"
        log_next "A host with no remote cameras wants compose.ports.yaml in COMPOSE_FILE instead."
        return
    fi

    if grep -q 'REPLACE_WITH' "$WG_CONF"; then
        fail "wireguard/wg0.conf still contains REPLACE_WITH placeholders."
        return
    fi

    local mode; mode="$(stat -c '%a' "$WG_CONF" 2>/dev/null || stat -f '%Lp' "$WG_CONF" 2>/dev/null || echo '')"
    if [[ -n "$mode" && "$mode" != "600" ]]; then
        warn "wireguard/wg0.conf is mode $mode. It holds a private key."
        log_next "chmod 600 $WG_CONF"
    fi

    if [[ -e /dev/net/tun ]]; then
        log_ok "/dev/net/tun is present."
    else
        fail "/dev/net/tun does not exist. sudo modprobe tun, and make it persistent."
    fi

    if modinfo wireguard >/dev/null 2>&1 || [[ -d /sys/module/wireguard ]]; then
        log_ok "The host kernel has WireGuard."
    else
        warn "No WireGuard kernel module found. The sidecar falls back to userspace, which costs CPU."
        log_next "That cost lands on the same cores already decoding video. Check before blaming the detector."
    fi

    # The routing trap, checked rather than only documented.
    if grep -qE '^[[:space:]]*AllowedIPs[[:space:]]*=.*0\.0\.0\.0/0' "$WG_CONF"; then
        warn "AllowedIPs includes 0.0.0.0/0 — a full tunnel inside the container's namespace."
        log_next "LAN cameras, the mosquitto service and replies to LAN browsers all route into the tunnel."
        log_next "Split-tunnel to the camera subnets, or add PostUp rules carving the Docker subnet back out."
    else
        check_allowedips_overlap
    fi

    if grep -qE '^[[:space:]]*DNS[[:space:]]*=' "$WG_CONF"; then
        warn "DNS is set in wg0.conf. It rewrites resolv.conf for the whole namespace."
        log_next "Frigate then cannot resolve 'mosquitto' and reports an MQTT failure that looks unrelated."
    fi
}

