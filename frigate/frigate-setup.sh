# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒

check_storage() {
    log_step "Checking recording storage..."

    local media; media="$(env_get FRIGATE_MEDIA)"
    if [[ -z "$media" ]]; then
        fail "FRIGATE_MEDIA is not set in .env."
        return
    fi

    if [[ ! -d "$media" ]]; then
        fail "FRIGATE_MEDIA points at $media, which is not a directory."
        log_next "sudo mkdir -p $media && sudo chown -R \$(id -u):\$(id -g) $media"
        return
    fi

    if [[ ! -w "$media" ]]; then
        fail "$media is not writable by $(id -un). Frigate records as UID $(id -u)."
        log_next "sudo chown -R \$(id -u):\$(id -g) $media"
        return
    fi

    local mp free
    mp="$(df -P "$media" 2>/dev/null | tail -n1 | awk '{print $6}')"
    free="$(df -Ph "$media" 2>/dev/null | tail -n1 | awk '{print $4}')"
    log_ok "$media is writable — mount point $mp, $free free."

    # The SD-card case. On a Pi this is not a stylistic preference.
    if [[ "$mp" == "/" ]]; then
        local model; model="$(host_model)"
        if [[ "$model" == *"Raspberry Pi"* ]]; then
            warn "Recordings are on the root filesystem of a $model — almost certainly the SD card."
            log_next "Continuous recording will wear an SD card out in months. Point FRIGATE_MEDIA at a USB SSD."
        else
            warn "Recordings are on the root filesystem. Fine if that is real storage; check it is not eMMC or an SD card."
        fi
    fi

    # Free space against the retention actually configured.
    local cont; cont="$(grep -A2 -E '^[[:space:]]*continuous:' "$CONFIG_FILE" 2>/dev/null \
        | grep -E '^[[:space:]]*days:' | head -n1 | awk '{print $2}' || true)"
    local cams; cams="$(awk '/^cameras:/{f=1;next} /^[a-z]/{f=0} f && /^  [a-z_]+:/{c++} END{print c+0}' "$CONFIG_FILE" 2>/dev/null || echo 0)"
    if [[ "$cont" =~ ^[0-9]+$ ]] && (( cont > 0 )) && (( cams > 0 )); then
        local need=$(( cont * cams * 21 ))
        log_info "Continuous retention is ${cont}d across ${cams} camera(s): roughly ${need} GB at 2 MB/s each."
    fi
}

