# On a fresh copy of this folder, seed .env and config.yml from the examples
# and stop. Both need decisions the script cannot make.
seed_if_missing() {
    local seeded=0

    if [[ ! -f "$ENV_FILE" ]]; then
        cp "$ENV_EXAMPLE" "$ENV_FILE"
        log_ok "Created .env from .env.example."
        seeded=1
    fi

    if [[ ! -f "$CONFIG_FILE" ]]; then
        cp "$CONFIG_EXAMPLE" "$CONFIG_FILE"
        log_ok "Created config/config.yml from config.yml.example."
        seeded=1
    fi

    if (( seeded )); then
        log_phase "EDIT THESE, THEN RUN AGAIN"
        log_next "\$EDITOR $ENV_FILE"
        log_next "   COMPOSE_FILE, FRIGATE_IMAGE, FRIGATE_MEDIA, TZ, RTSP credentials"
        log_next "\$EDITOR $CONFIG_FILE"
        log_next "   the detector block matching COMPOSE_FILE, then your cameras"
        log_next "./frigate-setup.sh"
        exit 0
    fi
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                             PROFILE COHERENCE
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
# The one thing nothing else catches: COMPOSE_FILE and config.yml each name a
# detector, independently, and a mismatch starts cleanly and then detects
# nothing. This is the check the whole script exists for.

DETECTOR=""           # openvino | coral-usb | hailo | rpi | cpu
NETWORK=""            # ports | wireguard

check_profile() {
    log_step "Checking profile selection..."

    local cf; cf="$(env_get COMPOSE_FILE)"
    if [[ -z "$cf" ]]; then
        fail "COMPOSE_FILE is not set in .env. Nothing selects a detector or a network overlay."
        return
    fi

    [[ "$cf" == *compose.yaml* ]] || fail "COMPOSE_FILE does not include the base compose.yaml."

    # Exactly one network overlay.
    local n=0
    [[ "$cf" == *compose.ports.yaml* ]]     && { NETWORK=ports;     n=$(( n + 1 )); }
    [[ "$cf" == *compose.wireguard.yaml* ]] && { NETWORK=wireguard; n=$(( n + 1 )); }
    if (( n == 0 )); then
        fail "COMPOSE_FILE names no network overlay. Add compose.ports.yaml or compose.wireguard.yaml."
    elif (( n > 1 )); then
        fail "COMPOSE_FILE names both network overlays. Frigate cannot publish ports and join a namespace."
    fi

    # Exactly one detector overlay.
    local d=0
    [[ "$cf" == *compose.openvino.yaml* ]]  && { DETECTOR=openvino;  d=$(( d + 1 )); }
    [[ "$cf" == *compose.coral-usb.yaml* ]] && { DETECTOR=coral-usb; d=$(( d + 1 )); }
    [[ "$cf" == *compose.hailo.yaml* ]]     && { DETECTOR=hailo;     d=$(( d + 1 )); }
    [[ "$cf" == *compose.rpi.yaml* ]]       && { DETECTOR=rpi;       d=$(( d + 1 )); }
    [[ "$cf" == *compose.cpu.yaml* ]]       && { DETECTOR=cpu;       d=$(( d + 1 )); }
    if (( d == 0 )); then
        fail "COMPOSE_FILE names no detector overlay."
    elif (( d > 1 )); then
        fail "COMPOSE_FILE names $d detector overlays. Pick one."
    fi

    (( FAILURES )) && return
    log_ok "Profile: $DETECTOR detection, $NETWORK networking."
}

# What config.yml actually asks for, reading only uncommented lines.
config_detector() {
    grep -E '^[[:space:]]+type:[[:space:]]*(openvino|edgetpu|hailo8l|cpu)[[:space:]]*$' \
        "$CONFIG_FILE" 2>/dev/null | awk '{print $2}' | sort -u
}

check_detector_agreement() {
    [[ -n "$DETECTOR" ]] || return 0
    log_step "Checking that config.yml agrees with the overlay..."

    local want found
    case "$DETECTOR" in
        openvino)  want=openvino ;;
        coral-usb) want=edgetpu ;;
        hailo)     want=hailo8l ;;
        rpi|cpu)   want=cpu ;;
    esac

    found="$(config_detector | tr '\n' ' ' | sed 's/ $//')"

    if [[ -z "$found" ]]; then
        fail "config.yml has no uncommented detector block. Uncomment the $want one."
    elif [[ "$found" != "$want" ]]; then
        fail "Mismatch: COMPOSE_FILE selects '$DETECTOR' (type: $want), config.yml declares 'type: $found'."
        log_next "Frigate would start, load the wrong detector, and detect nothing on hardware it cannot open."
    else
        log_ok "config.yml declares 'type: $want', which matches the overlay."
    fi
}

