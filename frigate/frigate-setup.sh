check_jwt_secret() {
    log_step "Checking the session signing secret..."

    local secret; secret="$(env_get FRIGATE_JWT_SECRET)"

    if [[ -n "$secret" ]]; then
        if (( ${#secret} < 64 )); then
            fail "FRIGATE_JWT_SECRET is ${#secret} characters. Frigate requires at least 64."
        else
            log_ok "FRIGATE_JWT_SECRET is set (${#secret} characters)."
        fi
        return
    fi

    if (( CHECK_ONLY )); then
        warn "FRIGATE_JWT_SECRET is empty. Frigate would mint a new one each start and log everyone out."
        return
    fi

    if ! command -v openssl >/dev/null 2>&1; then
        warn "FRIGATE_JWT_SECRET is empty and openssl is not installed. Set it by hand: 64+ characters."
        return
    fi

    secret="$(openssl rand -hex 32)"
    env_set FRIGATE_JWT_SECRET "$secret"
    log_ok "Generated FRIGATE_JWT_SECRET and wrote it to .env. Sessions now survive restarts."
}

