# Best-effort host identification, used only to make the advice specific.
host_model() {
    if [[ -r /proc/device-tree/model ]]; then
        tr -d '\0' < /proc/device-tree/model
    elif [[ -r /sys/devices/virtual/dmi/id/product_name ]]; then
        cat /sys/devices/virtual/dmi/id/product_name
    else
        uname -m
    fi
}

check_docker() {
    log_step "Checking Docker..."

    if ! command -v docker >/dev/null 2>&1; then
        fail "docker is not installed or not on PATH."
        return
    fi

    if ! docker info >/dev/null 2>&1; then
        fail "Cannot talk to the Docker daemon. Is it running, and are you in the docker group?"
        return
    fi

    if docker compose version >/dev/null 2>&1; then
        DC=(docker compose)
    elif command -v docker-compose >/dev/null 2>&1; then
        DC=(docker-compose)
        warn "Using legacy docker-compose. This stack expects the Compose v2 plugin."
    else
        fail "Docker Compose is not available. Install the docker-compose-plugin package."
        return
    fi

    log_ok "Docker is up: $(docker --version | cut -d, -f1), $("${DC[@]}" version --short 2>/dev/null || echo unknown)."
}

