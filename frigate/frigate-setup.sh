    log_ok "Containers are up."
    return 0
}

# Frigate prints a generated admin password on its first start, inside a block
# of asterisks. It does not always reprint it — see the reset_admin_password
# note if this comes up empty.
show_admin_password() {
    log_step "Waiting for Frigate to finish starting..."

    local attempt pw=""
    for attempt in $(seq 1 60); do
        : "$attempt"
        pw="$(cd "$SCRIPT_DIR" && "${DC[@]}" logs frigate 2>&1 \
              | grep -aoE 'Password:[[:space:]]*[^[:space:]*]+' \
              | tail -n1 | awk '{print $2}' || true)"
        [[ -n "$pw" ]] && break
        if (cd "$SCRIPT_DIR" && "${DC[@]}" logs frigate 2>&1 | grep -qa 'Capture process started'); then
            break
        fi
        sleep 2
    done

    if [[ -n "$pw" ]]; then
        log_phase "FIRST LOGIN"
        log_info "User:     admin"
        log_info "Password: $pw"
        log_warn "Change this at Settings > Users before creating any other account."
        log_next "On 0.17.2 any authenticated user can read the container log, and this password is in it."
    else
        log_info "No generated password in the log — normal if this instance has been started before."
        log_next "Locked out? Set auth.reset_admin_password: true in config.yml, restart, read the log, set it back."
    fi
}

report() {
    local ui_port; ui_port="$(env_get FRIGATE_UI_PORT)"; ui_port="${ui_port:-8971}"
    local rtsp_port; rtsp_port="$(env_get FRIGATE_RTSP_PORT)"; rtsp_port="${rtsp_port:-8554}"

    log_phase "NEXT"
    log_next "UI:        https://$(hostname -s 2>/dev/null || echo localhost).local:${ui_port}   (self-signed; the warning is expected)"
    log_next "Restream:  rtsp://<this-host>:${rtsp_port}/<camera>   and   /birdseye"
    log_next "Logs:      ${DC[*]} logs -f frigate"
    if [[ "$NETWORK" == "wireguard" ]]; then
        log_next "Tunnel:    ${DC[*]} exec wireguard wg show"
        log_next "Restarting the sidecar drops LAN cameras and the UI too, not only the remote ones."
        log_next "           Always follow it with: ${DC[*]} restart frigate"
    fi
}

