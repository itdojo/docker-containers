usage() {
    cat <<'USAGE'
mediamtx-users.sh — build the MediaMTX internal-auth user database

  ./mediamtx-users.sh [-f|--file PATH] [-h|--help]

  -f, --file PATH   write somewhere other than ./config/users.env
  -h, --help        this text

The script prints any users the file already holds, asks whether this run
appends to them or replaces them, then collects username, password, role,
path scope and source-IP allowlist for each new user. Passwords are hashed
with argon2id and never stored in the clear.

Authentication stays off until config/mediamtx.yml uncomments:

    authMethod: internal
    authInternalUsers: []
USAGE
}

parse_args() {
    while (( $# )); do
        case "$1" in
            -f|--file) [[ -n "${2:-}" ]] || { log_err "--file needs a path."; exit 1; }
                       USERS_FILE="$2"; shift 2 ;;
            -h|--help) usage; exit 0 ;;
            *)         log_err "Unknown argument: $1"; usage >&2; exit 1 ;;
        esac
    done
}

