#                                                     PACKAGE MANAGER DETECTION
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒

detect_package_manager() {
    OS="$(uname -s)"
    if [[ "$OS" == "Darwin" ]]; then
        PKG_MGR="brew"
        SUDO=""
    else
        if   command -v apt-get >/dev/null 2>&1; then PKG_MGR="apt-get"
        elif command -v dnf     >/dev/null 2>&1; then PKG_MGR="dnf"
        fi
        SUDO="sudo"
    fi
    if [[ -z "$PKG_MGR" ]]; then
        log_warn "No supported package manager found; argon2 must already be installed."
    else
        log_info "Platform: $OS, package manager $PKG_MGR."
    fi
}

pkg_install() {
    local pkg="$1"
    case "$PKG_MGR" in
        brew)    brew install "$pkg" ;;
        apt-get) $SUDO apt-get update -qq && $SUDO DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "$pkg" ;;
        dnf)     $SUDO dnf install -y -q "$pkg" ;;
        *)       return 1 ;;
    esac
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                   ARGON2 (hashing dependency)
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒

ensure_argon2() {
    if command -v argon2 >/dev/null 2>&1; then
        log_ok "argon2 is already installed."
        return 0
    fi
    log_info "argon2 hashes the passwords; it is a small standalone CLI."
    if ! ask_confirm "Install argon2 with $PKG_MGR?" Y; then
        log_err "argon2 is required. Install it and rerun:  $PKG_MGR install argon2"
        exit 1
    fi
    log_step "Installing argon2..."
    if ! pkg_install argon2 || ! command -v argon2 >/dev/null 2>&1; then
        log_err "argon2 did not install. Install it by hand and rerun."
        exit 1
    fi
    log_ok "argon2 is installed."
}

# argon2id at the CLI defaults (m=4096, t=3, p=1), matching what MediaMTX
# documents. Verification runs per request and HLS asks often, so a heavier
# profile costs the Pi on every segment, not once at login.
hash_password() {
    local pass="$1" salt
    salt="$(dd if=/dev/urandom bs=256 count=1 2>/dev/null \
            | LC_ALL=C tr -dc 'A-Za-z0-9' \
            | cut -c1-"$SALT_LEN")"
    if (( ${#salt} < 8 )); then
        log_err "Could not draw a $SALT_LEN-character salt from /dev/urandom."
        exit 1
    fi
    printf 'argon2:%s' "$(printf '%s' "$pass" | argon2 "$salt" -id -l "$ARGON2_HASH_LEN" -e)"
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                    USERS FILE — READING WHAT IS ALREADY THERE
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒

# Values are written single-quoted so Compose leaves the `$` in an argon2 hash
# alone. Strip the quotes on the way back in.
_unquote() {
    local v="$1"
    case "$v" in
        \'*\') v="${v#\'}"; v="${v%\'}" ;;
        \"*\") v="${v#\"}"; v="${v%\"}" ;;
    esac
    printf '%s' "$v"
}

_kv() {
    local f="$1" key="$2" v
    v="$(grep -m1 "^MTX_AUTHINTERNALUSERS_${key}=" "$f" 2>/dev/null || true)"
    [[ -z "$v" ]] && return 0
    _unquote "${v#*=}"
}

_indices() {
    sed -n 's/^MTX_AUTHINTERNALUSERS_\([0-9][0-9]*\)_.*/\1/p' "$1" | sort -n -u
}

_perm_indices() {
    sed -n "s/^MTX_AUTHINTERNALUSERS_$2_PERMISSIONS_\([0-9][0-9]*\)_.*/\1/p" "$1" | sort -n -u
}

# Load every user except the managed tail entry — render_users_file writes a
# fresh one, so keeping the old copy would duplicate it on every append.
load_existing() {
    local f="$1" i j u p ips act path perms
    for i in $(_indices "$f"); do
        u="$(_kv "$f" "${i}_USER")"
        [[ -z "$u" ]] && continue
        p="$(_kv "$f" "${i}_PASS")"
        ips="$(_kv "$f" "${i}_IPS")"
        perms=""
        for j in $(_perm_indices "$f" "$i"); do
            act="$(_kv "$f" "${i}_PERMISSIONS_${j}_ACTION")"
            [[ -z "$act" ]] && continue
            path="$(_kv "$f" "${i}_PERMISSIONS_${j}_PATH")"
            perms="${perms}${act}|${path}
"
        done
        if [[ "$u" == "any" && "$perms" == *"api|"* ]]; then
            continue
        fi
        ENTRY_USER+=("$u")
        ENTRY_PASS+=("$p")
        ENTRY_IPS+=("$ips")
        ENTRY_PERMS+=("$perms")
        ENTRY_ORIGIN+=("kept")
    done
}

perms_summary() {
    local perms="$1" line act path out=""
    while IFS= read -r line; do
        [[ -z "$line" ]] && continue
        act="${line%%|*}"; path="${line#*|}"
        [[ -z "$path" ]] && path="*"
        out="$out $act:$path"
    done <<< "$perms"
    printf '%s' "${out# }"
}

show_entries() {
    local i n
    n="${#ENTRY_USER[@]}"
    printf '         %s%-3s %-18s %-38s %-18s %s%s\n' \
        "$QOL_META" "IDX" "USER" "PERMISSIONS" "SOURCE IPS" "ORIGIN" "$QOL_RESET"
    for (( i = 0; i < n; i++ )); do
        printf '         %-3s %-18s %-38s %-18s %s\n' \
            "$i" "${ENTRY_USER[$i]}" \
            "$(perms_summary "${ENTRY_PERMS[$i]}")" \
            "${ENTRY_IPS[$i]:-any}" \
            "${ENTRY_ORIGIN[$i]}"
    done
}

# Decides MODE, and returns 1 when the user chose to walk away.
review_existing() {
    local choice
    if [[ ! -f "$USERS_FILE" ]]; then
        log_info "No users file yet — this run creates $USERS_FILE."
        MODE="overwrite"
        return 0
    fi
    load_existing "$USERS_FILE"
    if (( ${#ENTRY_USER[@]} == 0 )); then
        log_warn "$USERS_FILE exists but defines no users. Treating this run as a fresh write."
        MODE="overwrite"
        return 0
    fi
    HAD_FILE=1
    log_ok "$USERS_FILE already defines ${#ENTRY_USER[@]} user(s):"
    show_entries
    choice="$(ask_choice "THIS RUN SHOULD" 1 \
        "append|keep the users above and add more" \
        "overwrite|discard them; a timestamped backup is taken first" \
        "quit|change nothing and exit")"
    case "$choice" in
        1) MODE="append";    log_ok "Appending to the existing ${#ENTRY_USER[@]} user(s)." ;;
        2) MODE="overwrite"
           ENTRY_USER=(); ENTRY_PASS=(); ENTRY_IPS=(); ENTRY_PERMS=(); ENTRY_ORIGIN=()
           log_warn "Overwriting. The current file is backed up before it is replaced." ;;
        *) return 1 ;;
    esac
    return 0
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                QUESTIONS — ONE USER AT A TIME
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒

user_exists() {
    local want="$1" i
    for (( i = 0; i < ${#ENTRY_USER[@]}; i++ )); do
        [[ "${ENTRY_USER[$i]}" == "$want" ]] && return 0
    done
    return 1
}

# This function's stdout IS its return value, so every complaint it makes goes
# to stderr — the same split ask_value already uses. A log_warn left on stdout
# would be captured and concatenated onto the username.
ask_username() {
    local u
    while true; do
        u="$(ask_value "Username" "" "letters, digits, dot, dash, underscore")"
        if [[ -z "$u" ]]; then
            log_warn "A username is required." >&2
        elif [[ ! "$u" =~ ^[A-Za-z0-9._-]+$ ]]; then
            log_warn "Use only letters, digits, dot, dash and underscore." >&2
        elif [[ "$u" == "any" ]]; then
            log_warn "\"any\" is reserved — MediaMTX reads it as the anonymous user." >&2
        elif user_exists "$u"; then
            log_warn "\"$u\" is already in this list. Pick another name." >&2
        else
            printf '%s' "$u"
            return 0
        fi
    done
}

# Not ask_value: it echoes what you type, and a password must not appear on
# screen or in the scrollback. Borrowing the chrome keeps the prompt identical
# to every other question while the read stays ours.
#
# Echo is killed with stty before the prompt is drawn, not left to `read -rs`.
# read only disables echo once it starts, so anything typed between the prompt
# printf and the read still lands on screen — a narrow window, but one a fast
# typist and every expect-driven test walks straight into.
#
# The answer comes back in PASSWORD_IN rather than on stdout, because $(...)
# would run all of this in a subshell and STTY_SAVED would die with it — and
# then a CTRL-C at the password prompt would hand back a shell with echo off.
ask_password() {
    local who="$1" p1 p2
    PASSWORD_IN=""
    STTY_SAVED="$(stty -g 2>/dev/null || true)"
    [[ -n "$STTY_SAVED" ]] && stty -echo 2>/dev/null
    while true; do
        _log_line "$QOL_STEP" ASK "Password for $who (minimum $MIN_PASS_LEN characters)" >&2
        printf '    %s❯%s %s[hidden]%s ' "$QOL_PASS" "$QOL_RESET" "$QOL_META" "$QOL_RESET" >&2
        IFS= read -rs p1; printf '\n' >&2
        if (( ${#p1} < MIN_PASS_LEN )); then
            log_warn "Too short — ${#p1} characters, minimum is $MIN_PASS_LEN."
            continue
        fi
        printf '    %s❯%s %sagain%s ' "$QOL_PASS" "$QOL_RESET" "$QOL_META" "$QOL_RESET" >&2
        IFS= read -rs p2; printf '\n' >&2
        if [[ "$p1" != "$p2" ]]; then
            log_warn "The two entries do not match."
            continue
        fi
        restore_tty
        PASSWORD_IN="$p1"
        return 0
    done
}

ask_role_perms() {
    local who="$1" choice path actions act out=""
    choice="$(ask_choice "ROLE FOR $who" 3 \
        "publisher|publish and read" \
        "viewer|read and play back recordings" \
        "full|publish, read and play back" \
        "admin|full, plus api, metrics and pprof")"
    case "$choice" in
        1) actions="publish read" ;;
        2) actions="read playback" ;;
        3) actions="publish read playback" ;;
        *) actions="publish read playback admin" ;;
    esac

    path="$(ask_value "Path scope for $who" "all" "a stream name such as cam, or \"all\"")"
    if [[ "$path" == "all" || -z "$path" ]]; then
        path=""
    elif [[ ! "$path" =~ ^[A-Za-z0-9._/-]+$ ]]; then
        # stderr: this function's stdout is the permission list it returns.
        log_warn "\"$path\" is not a usable path name; falling back to all paths." >&2
        path=""
    fi

    for act in $actions; do
        if [[ "$act" == "admin" ]]; then
            # api, metrics and pprof are server-wide; a path would mean nothing.
            out="${out}api|
metrics|
pprof|
"
        else
            out="${out}${act}|${path}
"
        fi
    done
    printf '%s' "$out"
}

ask_ips() {
    local who="$1" ips
    while true; do
        ips="$(ask_value "Source addresses allowed for $who" "any" \
                         "comma-separated IPs or CIDRs, or \"any\"")"
        if [[ "$ips" == "any" || -z "$ips" ]]; then
            printf ''
            return 0
        fi
        if [[ "$ips" =~ ^[0-9A-Fa-f:./,]+$ ]]; then
            printf '%s' "$ips"
            return 0
        fi
        # stderr, for the same reason as ask_username.
        log_warn "Use IPv4/IPv6 addresses or CIDRs separated by commas, or \"any\"." >&2
    done
}

collect_one_user() {
    local u p perms ips hash
    u="$(ask_username)"
    ask_password "$u"
    p="$PASSWORD_IN"; PASSWORD_IN=""
    perms="$(ask_role_perms "$u")"
    ips="$(ask_ips "$u")"

    log_step "Hashing the password for $u..."
    hash="$(hash_password "$p")"
    p=""
    log_ok "$u will be stored as argon2id."

    ENTRY_USER+=("$u")
    ENTRY_PASS+=("$hash")
    ENTRY_IPS+=("$ips")
    ENTRY_PERMS+=("$perms")
    ENTRY_ORIGIN+=("new")
    ADDED_THIS_RUN=$(( ADDED_THIS_RUN + 1 ))
}

collect_users() {
    while true; do
        collect_one_user
        ask_confirm "Add another user?" N || break
    done
    log_ok "$ADDED_THIS_RUN user(s) collected. Full list:"
    show_entries
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                      WRITING config/users.env
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒

# cat over the destination rather than mv a temp onto it: mv would carry the
# temp file's 0600 mode and a new inode, and quietly break anything watching
# the path. The chmod that follows is deliberate, not inherited.
replace_file_contents() {
    local src="$1" dst="$2"
    cat "$src" > "$dst"
}

backup_users_file() {
    local stamp bak
    [[ -f "$USERS_FILE" ]] || return 0
    stamp="$(date +%Y%m%d-%H%M%S)"
    bak="$USERS_FILE.pre-mediamtx-users.$stamp.bak"
    cp "$USERS_FILE" "$bak"
    chmod 600 "$bak"
    log_ok "Backed up to $(basename "$bak")."
}

render_users_file() {
    local out="$1" i j n line act path
    n="${#ENTRY_USER[@]}"
    {
        cat <<'HEADER'
# MediaMTX internal-authentication users — generated by mediamtx-users.sh.
# Rerun that script to change this file; it shows the list below and asks
# before touching it. Hand edits survive, but nothing validates them.
#
# Every value is single-quoted on purpose. Compose interpolates unquoted
# env_file values, and an argon2 hash starts with `$argon2id`, which reads as
# a variable reference and expands to nothing.
#
# This file is inert until config/mediamtx.yml uncomments both
# `authMethod: internal` and `authInternalUsers: []`. The empty list is not
# optional: MediaMTX merges these variables into the built-in user list field
# by field rather than replacing it, so a permission you never granted can
# survive from the built-in entry at the same index.
HEADER
        printf '#\n# Written %s by %s.\n' "$(date +%Y-%m-%d\ %H:%M:%S)" "${USER:-$(id -un)}"

        for (( i = 0; i < n; i++ )); do
            printf '\n# ‒‒ user %d — %s — %s — from %s ‒‒\n' \
                "$i" "${ENTRY_USER[$i]}" \
                "$(perms_summary "${ENTRY_PERMS[$i]}")" \
                "${ENTRY_IPS[$i]:-any address}"
            printf "MTX_AUTHINTERNALUSERS_%d_USER='%s'\n" "$i" "${ENTRY_USER[$i]}"
            printf "MTX_AUTHINTERNALUSERS_%d_PASS='%s'\n" "$i" "${ENTRY_PASS[$i]}"
            printf "MTX_AUTHINTERNALUSERS_%d_IPS='%s'\n"  "$i" "${ENTRY_IPS[$i]}"
            j=0
            while IFS= read -r line; do
                [[ -z "$line" ]] && continue
                act="${line%%|*}"; path="${line#*|}"
                printf "MTX_AUTHINTERNALUSERS_%d_PERMISSIONS_%d_ACTION='%s'\n" "$i" "$j" "$act"
                case "$act" in
                    api|metrics|pprof) : ;;
                    *) printf "MTX_AUTHINTERNALUSERS_%d_PERMISSIONS_%d_PATH='%s'\n" "$i" "$j" "$path" ;;
                esac
                j=$(( j + 1 ))
            done <<< "${ENTRY_PERMS[$i]}"
        done

        cat <<TAIL

# ‒‒ managed tail entry — do not renumber ‒‒
# With authInternalUsers emptied in mediamtx.yml, the built-in localhost API
# user is gone too. This puts it back, so \`docker compose exec\`-style API
# calls and the metrics endpoint still answer on the Pi itself.
MTX_AUTHINTERNALUSERS_${n}_USER='any'
MTX_AUTHINTERNALUSERS_${n}_PASS=''
MTX_AUTHINTERNALUSERS_${n}_IPS='127.0.0.1,::1'
MTX_AUTHINTERNALUSERS_${n}_PERMISSIONS_0_ACTION='api'
MTX_AUTHINTERNALUSERS_${n}_PERMISSIONS_1_ACTION='metrics'
MTX_AUTHINTERNALUSERS_${n}_PERMISSIONS_2_ACTION='pprof'
TAIL
    } > "$out"
}

write_users_file() {
    local tmp dir
    dir="$(dirname "$USERS_FILE")"
    [[ -d "$dir" ]] || mkdir -p "$dir"
    backup_users_file
    tmp="$(mktemp "${TMPDIR:-/tmp}/mediamtx-users.XXXXXX")"
    chmod 600 "$tmp"
    render_users_file "$tmp"
    if [[ -f "$USERS_FILE" ]]; then
        replace_file_contents "$tmp" "$USERS_FILE"
    else
        cp "$tmp" "$USERS_FILE"
    fi
    rm -f "$tmp"
    chmod 600 "$USERS_FILE"
    WROTE_FILE=1
    if (( ! HAD_FILE )); then
        log_info "New file: $ADDED_THIS_RUN user(s) written."
    else
        case "$MODE" in
            append)    log_info "Append: $(( ${#ENTRY_USER[@]} - ADDED_THIS_RUN )) kept, $ADDED_THIS_RUN added." ;;
            overwrite) log_info "Overwrite: the previous list was replaced." ;;
        esac
    fi
    log_ok "Wrote ${#ENTRY_USER[@]} user(s) plus the localhost API entry to $USERS_FILE (mode 600)."
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                                 WIRING CHECKS
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒

# The file only does something if two other files agree with it. Say so here
# rather than letting the user discover it as a stream that never asks for a
# password.
check_wiring() {
    local yml_ok=0 compose_ok=0
    if [[ -f "$MEDIAMTX_YML" ]] \
       && grep -qE '^[[:space:]]*authInternalUsers:[[:space:]]*\[\][[:space:]]*$' "$MEDIAMTX_YML"; then
        yml_ok=1
    fi
    if [[ -f "$COMPOSE_FILE" ]] && grep -q 'config/users.env' "$COMPOSE_FILE"; then
        compose_ok=1
    fi

    if (( yml_ok )); then
        log_ok "config/mediamtx.yml has authInternalUsers: [] uncommented — authentication is armed."
    else
        log_warn "config/mediamtx.yml still has authentication commented out; these users are inert."
    fi
    if (( compose_ok )); then
        log_ok "compose.yaml loads config/users.env."
    else
        log_warn "compose.yaml does not reference config/users.env; the container will never see these users."
    fi
}

