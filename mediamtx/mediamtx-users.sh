# ask_password turns terminal echo off around its reads. Dying in that window
# would hand the user back a shell that does not show what they type, so both
# traps restore the saved state before they say anything.
restore_tty() {
    [[ -n "$STTY_SAVED" ]] && stty "$STTY_SAVED" 2>/dev/null
    STTY_SAVED=""
    return 0
}

handle_ctrl_c() {
    restore_tty
    printf '\n' >&2
    if (( WROTE_FILE )); then
        log_warn "Interrupted after the file was written. $USERS_FILE is complete."
    else
        log_warn "Interrupted. Nothing was written."
    fi
    exit 130
}
trap handle_ctrl_c INT

handle_err() {
    local code=$? line="$1"
    restore_tty
    log_err "Failed at line $line (exit $code). $USERS_FILE was not modified."
    exit "$code"
}
trap 'handle_err $LINENO' ERR

check_for_root() {
    if [[ "${EUID:-$(id -u)}" -eq 0 ]]; then
        log_err "Do not run this as root. It writes a file you must own; rerun as yourself."
        exit 1
    fi
}

# Every value here comes from a prompt, and a password cannot have a default.
# ASSUME_YES would make ask_value hand back empty strings in silence, so the
# script refuses it outright rather than writing a user with no password.
require_interactive() {
    if [[ -n "${ASSUME_YES:-}" ]]; then
        log_err "ASSUME_YES is set. This script cannot run unattended — unset it and rerun."
        exit 1
    fi
    if [[ ! -t 0 || ! -t 1 ]]; then
        log_err "No TTY. Run this from a terminal, not a pipe or a cron job."
        exit 1
    fi
}

