main() {
    parse_args "$@"
    banner "MEDIAMTX USER MANAGER" "internal auth · argon2id"

    check_for_root
    require_interactive

    log_phase "PREFLIGHT"
    detect_package_manager
    ensure_argon2
    log_info "Users file: $USERS_FILE"

    log_phase "EXISTING USERS"
    if ! review_existing; then
        log_ok "Nothing changed. $USERS_FILE is as you left it."
        log_complete "NO CHANGES WRITTEN"
        echo
        return 0
    fi

    log_phase "NEW USERS"
    collect_users

    if (( ADDED_THIS_RUN == 0 )); then
        log_warn "No users were added, so the file was not rewritten."
        log_complete "NO CHANGES WRITTEN"
        echo
        return 0
    fi

    log_phase "WRITE"
    write_users_file

    log_phase "WIRING"
    check_wiring

    log_complete "USERS WRITTEN"
    log_next "Uncomment authMethod and authInternalUsers in config/mediamtx.yml."
    log_next "Restart the stack:  docker compose up -d"
    log_next "Test:  ffplay rtsp://<user>:<password>@<pi>:8554/cam"
    log_next "users.env holds password hashes at mode 600 — keep it out of git."
    echo
}

main "$@"
