#!/usr/bin/env bash
#
# mediamtx-users.sh
#
# Generates config/users.env — the MediaMTX internal-authentication user
# database, as MTX_AUTHINTERNALUSERS_* environment variables that compose
# hands to the container. Passwords are hashed with argon2id; the plaintext
# never reaches disk.
#
# Targets:
#   - macOS                        (Homebrew)
#   - Debian / Ubuntu / Pi OS      (apt-get)
#   - Fedora / RHEL / Rocky / Alma (dnf)
#
# Usage:  ./mediamtx-users.sh [-f|--file PATH] [-h|--help]
# Do not run as root.  Needs a TTY: every value comes from a prompt.
#
# The script is idempotent in the sense that matters: it shows you what is
# already in the file before it touches it, and asks whether this run appends
# to that list or replaces it. An overwrite takes a timestamped backup first.
#
# Turning authentication on takes two more steps the script cannot do for you,
# because both are decisions: uncomment `authMethod` and `authInternalUsers`
# in config/mediamtx.yml, then `docker compose up -d`. The closing NEXT lines
# repeat them, and the script warns if either looks undone.
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒

